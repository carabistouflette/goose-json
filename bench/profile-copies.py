"""Count phase-scoped encoder copies and allocation calls; not a timing tool.

Linux/GNU ld only. Instruments a generated standalone C translation unit and
wraps malloc/calloc/realloc/free from statically linked objects. The codec and
compiler installations are never edited. Counts exclude setup and warmup.
"""
import argparse
import csv
import hashlib
import json
import os
import shlex
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[1]
ENTRY = ROOT / 'bench/results/sparse-prefix-native-2026-11-05/paired.goose'
FIXTURES = ('plain', 'escaped', 'array', 'array-signed', 'array-wide', 'mixed',
            'floats', 'floats-wide', 'text-short', 'text-sparse', 'text-ascii',
            'text-escaped', 'wide')
COUNTERS = ('copy_calls', 'copy_bytes', 'regions', 'malloc', 'calloc', 'realloc', 'free')

PREFIX = """
static int gj_probe_active;
static unsigned long long gj_probe_counts[7];
"""
FOOTER = r"""
void *__real_malloc(size_t);
void *__real_calloc(size_t, size_t);
void *__real_realloc(void *, size_t);
void __real_free(void *);
void *__wrap_malloc(size_t n) {
    if (gj_probe_active) gj_probe_counts[3]++;
    return __real_malloc(n);
}
void *__wrap_calloc(size_t n, size_t size) {
    if (gj_probe_active) gj_probe_counts[4]++;
    return __real_calloc(n, size);
}
void *__wrap_realloc(void *p, size_t n) {
    if (gj_probe_active) gj_probe_counts[5]++;
    return __real_realloc(p, n);
}
void __wrap_free(void *p) {
    if (gj_probe_active) gj_probe_counts[6]++;
    __real_free(p);
}
void gj_probe_begin(void) {
    for (int i = 0; i < 7; i++) gj_probe_counts[i] = 0;
    gj_probe_active = 1;
}
void gj_probe_end(void) {
    gj_probe_active = 0;
    fprintf(stderr, "%llu,%llu,%llu,%llu,%llu,%llu,%llu\n",
        gj_probe_counts[0], gj_probe_counts[1], gj_probe_counts[2],
        gj_probe_counts[3], gj_probe_counts[4], gj_probe_counts[5], gj_probe_counts[6]);
}
"""

def run(args, **kwargs):
    return subprocess.run(args, check=True, cwd=ROOT, **kwargs)

def capture(args):
    return run(args, stdout=subprocess.PIPE, text=True).stdout.strip()

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def instrument(text):
    copy = 'static void gs_memcpy(void *dst, const void *src, size_t n) {'
    region = 'GS_API uint8_t *gs_reserve_region(gs_stack *stack) {'
    for marker in (copy, region):
        if text.count(marker) != 1:
            raise RuntimeError('unsupported runtime: expected exactly one ' + marker)
    text = text.replace(copy, PREFIX + copy +
        '\n    if (gj_probe_active) { gj_probe_counts[0]++; gj_probe_counts[1] += n; }')
    text = text.replace(region, region +
        '\n    if (gj_probe_active) gj_probe_counts[2]++;')
    return text + FOOTER

def cc(args):
    # Goose also probes compiler identity; only rewrite the generated program.
    paths = [Path(arg) for arg in args if arg.endswith('.c') and Path(arg).is_file()
             and Path(arg).read_text().startswith('/* Generated by the Goose compiler')]
    if paths:
        if len(paths) != 1:
            raise RuntimeError('expected one generated C input')
        original = paths[0]
        rewritten = original.with_name(original.stem + '-copy-probe.c')
        rewritten.write_text(instrument(original.read_text()))
        args = [str(rewritten) if arg == str(original) else arg for arg in args]
        args += ['-Wl,--wrap=' + name for name in ('malloc', 'calloc', 'realloc', 'free')]
    os.execvp('gcc', ['gcc', *args])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--goose', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--cpu', type=int, default=3)
    args = parser.parse_args()
    if args.cpu not in os.sched_getaffinity(0):
        parser.error('CPU is outside allowed affinity')
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    if any(output.iterdir()):
        parser.error('output must be empty')
    paths = capture(['git', 'ls-files', '--', 'json_codec.goose', 'json_codec.build',
                     'CMakeLists.txt', 'native', 'scripts/native-manifest.py',
                     'GOOSE_REVISION', 'bench/fixtures']).splitlines()
    paths += [str(ENTRY.relative_to(ROOT)), str(Path(__file__).resolve().relative_to(ROOT))]
    sources = {p: digest(ROOT / p) for p in paths}
    metadata = {'utc': datetime.now(timezone.utc).isoformat(),
                'flags': 'Goose -O2 --standalone; GCC -O2; native C++ Release -O3 -DNDEBUG; portable CPU defaults',
                'g++': capture(['g++', '--version']).splitlines()[0],
                'linker': capture(['ld', '--version']).splitlines()[0],
                'revision': capture(['git', 'rev-parse', 'HEAD']),
                'goose_version': capture([str(args.goose.resolve()), 'version']),
                'gcc': capture(['gcc', '--version']).splitlines()[0],
                'source_sha256': sources, 'cpu': args.cpu,
                'scope': 'Instrumented operation counts, not latency. Runtime gs_memcpy requests only; no claim to count every machine/native/libc copy. GNU ld wrapped allocation calls exclude internals of shared libraries. Setup/preflight/warmup excluded.',
                'validation': 'pending'}
    with tempfile.TemporaryDirectory(prefix='gj-copy-profile-') as directory:
        scratch = Path(directory)
        entry = scratch / 'profile.goose'
        text = ENTRY.read_text()
        old = 'import json_codec from "../../..";'
        assert text.count(old) == 1
        text = text.replace(old, 'import json_codec from ' + json.dumps(str(ROOT)) + ';')
        text += '\nextern fn probe_begin() = "gj_probe_begin";\nextern fn probe_end() = "gj_probe_end";\n'
        for old, new in [('    let started = clock_ns();', '    probe_begin();\n    let started = clock_ns();'),
                         ('    let elapsed = clock_ns() - started;', '    let elapsed = clock_ns() - started;\n    probe_end();')]:
            assert text.count(old) == 1
            text = text.replace(old, new)
        entry.write_text(text)
        wrapper = scratch / 'probe-cc'
        wrapper.write_text('#!/bin/sh\nexec ' + shlex.quote(shutil.which('python3')) + ' ' +
                           shlex.quote(str(Path(__file__).resolve())) + ' --internal-cc "$@"\n')
        wrapper.chmod(0o755)
        (scratch / 'g++').symlink_to(shutil.which('g++'))
        env = dict(os.environ, GOOSE_HOME=str(scratch / 'cache'))
        # Clear caller build-flag overrides for a controlled diagnostic build.
        for key in ('CFLAGS', 'CPPFLAGS', 'CXXFLAGS', 'LDFLAGS'):
            env.pop(key, None)
        binary = output / 'profile'
        with (output / 'build.log').open('w') as log:
            run(['taskset', '-c', str(args.cpu), str(args.goose.resolve()), 'build',
                 str(entry), '--standalone', '--cc', str(wrapper), '-O2', '-o', str(binary)],
                env=env, stdout=log, stderr=subprocess.STDOUT)
        metadata['binary_sha256'] = digest(binary)
        with (output / 'counts.csv').open('w', newline='') as stream:
            writer = csv.writer(stream, lineterminator='\n')
            writer.writerow(('fixture', 'iterations', 'encoded_bytes', 'checksum', *COUNTERS))
            for fixture in FIXTURES:
                first = None
                for iterations in (1, 10):
                    result = run(['taskset', '-c', str(args.cpu), str(binary), fixture, str(iterations)],
                                 stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
                    name, count, size, elapsed, checksum = result.stdout.strip().split(',')
                    counters = [int(n) for n in result.stderr.strip().split(',')]
                    assert name == fixture and int(count) == iterations and int(size) > 0
                    assert len(counters) == len(COUNTERS) and all(n >= 0 for n in counters)
                    if first is None:
                        first = (size, counters)
                    else:
                        if size != first[0] or counters != [10 * n for n in first[1]]:
                            raise RuntimeError('phase counts do not scale exactly 1:10: ' + fixture)
                    writer.writerow((name, count, size, checksum, *counters))
        if sources != {p: digest(ROOT / p) for p in paths}:
            raise RuntimeError('source changed during profiling')
        metadata['validation'] = 'passed: full existing fixture/bit-roundtrip preflight and per-iteration API assertions; source hashes unchanged'
    (output / 'metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')

if __name__ == '__main__':
    if sys.argv[1:2] == ['--internal-cc']:
        cc(sys.argv[2:])
    else:
        main()
